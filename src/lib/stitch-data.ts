// Pre-generated Bal Gandharva Ranga Mandir seats grid matching Stitch screen
export function generateStitchSeats(sessionId: number = 101): SeatItem[] {
  const seatsList: SeatItem[] = [];
  let seatIdCounter = 1;

  // Balcony Rows: A, B, C (₹500)
  const balconyRows = ['A', 'B', 'C'];
  balconyRows.forEach((row) => {
    for (let num = 1; num <= 8; num++) {
      const isAisle = num === 4;
      const isBooked = (row === 'A' && (num === 3 || num === 6 || num === 7)) ||
                       (row === 'B' && (num === 2 || num === 5)) ||
                       (row === 'C' && (num === 4 || num === 8));
      seatsList.push({
        id: seatIdCounter++,
        venueId: 1,
        sectionId: 1,
        rowLabel: row,
        seatNumber: num,
        seatCode: `BAL-${row}${num}`,
        tier: 'balcony',
        isAccessible: 0,
        status: isBooked ? 'booked' : 'available',
        price: 50000,
        sectionName: 'Balcony',
        sectionNameMr: 'बालकनी',
      });
    }
  });

  // Stall Rows: D, E, F, G, H (₹300)
  const stallRows = ['D', 'E', 'F', 'G', 'H'];
  stallRows.forEach((row) => {
    for (let num = 1; num <= 8; num++) {
      const isBooked = (row === 'D' && (num === 1 || num === 2 || num === 8)) ||
                       (row === 'E' && (num === 3 || num === 4 || num === 7)) ||
                       (row === 'F' && (num === 2 || num === 5 || num === 6)) ||
                       (row === 'G' && (num === 4 || num === 8)) ||
                       (row === 'H' && num === 1);
      seatsList.push({
        id: seatIdCounter++,
        venueId: 1,
        sectionId: 2,
        rowLabel: row,
        seatNumber: num,
        seatCode: `STL-${row}${num}`,
        tier: 'stall',
        isAccessible: row === 'H' && num <= 2 ? 1 : 0,
        status: isBooked ? 'booked' : 'available',
        price: 30000,
        sectionName: 'Stall',
        sectionNameMr: 'स्टॉल',
      });
    }
  });

  return seatsList;
}

export function getStitchEventById(id: number | string): EventItem | null {
  const numId = Number(id);
  const found = STITCH_EVENTS.find((e) => e.id === numId);
  return found || STITCH_EVENTS[0];
}
